export function resolveTheme(project) {
  const base = THEMES[project.theme] || THEMES.survey;
  const t = { ...base, ...(project.colors || {}) };
  t.tints = project.colors?.tints || base.tints;
  t.effects = { ...base.effects, ...(project.effects || {}) };
  return t;
}
